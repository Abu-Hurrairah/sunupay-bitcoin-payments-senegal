"""Bitcoin Core regtest JSON-RPC client. Never connects to mainnet."""
from __future__ import annotations

import base64
import json
import os
import time
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import quote
from urllib.request import Request, urlopen

SATOSHIS = Decimal("100000000")


class BitcoinError(Exception):
    pass


def btc_to_sats(amount: Decimal | str | int | float) -> int:
    value = Decimal(str(amount)) * SATOSHIS
    if value != value.to_integral_value(rounding=ROUND_HALF_UP):
        raise BitcoinError("Node returned an invalid Bitcoin precision")
    return int(value)


def sats_to_btc(sats: int) -> float:
    # Bitcoin Core's monetary amount RPC parameter is a JSON numeric amount.
    return float(Decimal(sats) / SATOSHIS)


class CoreRPC:
    def __init__(self, host: str | None = None, cookie: str | None = None):
        self.host = host or os.getenv("BITCOIN_RPC_URL", "http://bitcoin:18443")
        self.cookie = Path(cookie or os.getenv("BITCOIN_COOKIE", "/bitcoin/regtest/.cookie"))
        if not self.host.startswith("http://"):
            raise BitcoinError("Regtest RPC must use the isolated HTTP network")

    def call(self, method: str, params: list | None = None, wallet: str | None = None):
        try:
            credentials = self.cookie.read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise BitcoinError("Bitcoin Core is starting; RPC cookie is not ready") from exc
        if ":" not in credentials:
            raise BitcoinError("Bitcoin Core RPC cookie is invalid")
        url = self.host.rstrip("/")
        if wallet is not None:
            url += "/wallet/" + quote(wallet, safe="")
        body = json.dumps({"jsonrpc": "1.0", "id": "sunupay", "method": method, "params": params or []}).encode()
        encoded = base64.b64encode(credentials.encode()).decode()
        request = Request(url, data=body, headers={
            "Authorization": "Basic " + encoded,
            "Content-Type": "application/json",
        })
        try:
            with urlopen(request, timeout=35) as response:
                raw = response.read()
        except HTTPError as exc:
            try:
                payload = json.loads(exc.read().decode())
                message = (payload.get("error") or {}).get("message") or "Bitcoin Core RPC failed"
            except Exception:
                message = "Bitcoin Core RPC failed"
            raise BitcoinError(str(message)) from exc
        except (URLError, TimeoutError, OSError) as exc:
            raise BitcoinError("Bitcoin Core RPC is currently unavailable") from exc
        try:
            data = json.loads(raw, parse_float=Decimal)
        except ValueError as exc:
            raise BitcoinError("Invalid response received from Bitcoin Core") from exc
        if data.get("error"):
            raise BitcoinError(str(data["error"].get("message", "Bitcoin Core error")))
        return data["result"]

    def verify_regtest(self) -> int:
        info = self.call("getblockchaininfo")
        if info.get("chain") != "regtest":
            raise BitcoinError("Unsafe network: only Bitcoin regtest is supported")
        return int(info["blocks"])

    def ensure_wallet(self, wallet: str):
        # Wallet names are generated by our app, never taken from arbitrary input.
        loaded = self.call("listwallets")
        if wallet in loaded:
            return
        known = self.call("listwalletdir").get("wallets", [])
        if wallet in {item["name"] for item in known}:
            self.call("loadwallet", [wallet])
        else:
            self.call("createwallet", [wallet, False, False, "", False, True])

    def new_address(self, wallet: str, label: str = "") -> str:
        return self.call("getnewaddress", [label, "bech32"], wallet)

    def get_balance_sats(self, wallet: str) -> int:
        return btc_to_sats(self.call("getbalance", [], wallet))

    def send_sats(self, wallet: str, address: str, amount_sats: int) -> str:
        if not (546 <= amount_sats <= 2_100_000_000_000_000):
            raise BitcoinError("Invalid Bitcoin transaction amount")
        if not bool(self.call("validateaddress", [address]).get("isvalid")):
            raise BitcoinError("Recipient Bitcoin address is not valid")
        return self.call("sendtoaddress", [address, sats_to_btc(amount_sats)], wallet)

    def received_sats(self, wallet: str, address: str, confs: int) -> int:
        return btc_to_sats(self.call("getreceivedbyaddress", [address, confs], wallet))

    def history(self, wallet: str, count: int = 30):
        return self.call("listtransactions", ["*", count, 0, True], wallet)

    def mine(self, count: int = 1) -> int:
        if count < 1 or count > 110:
            raise BitcoinError("Mining request exceeds safety limit")
        self.ensure_wallet("sunupay_treasury")
        addr = self.new_address("sunupay_treasury", "regtest mining")
        self.call("generatetoaddress", [count, addr])
        return self.verify_regtest()

    def fund_customer(self, wallet: str, amount_sats: int = 5_000_000) -> str:
        self.verify_regtest()
        self.ensure_wallet("sunupay_treasury")
        if self.get_balance_sats("sunupay_treasury") < amount_sats + 100_000:
            self.mine(101)
        address = self.new_address(wallet, "Local regtest faucet")
        transaction_id = self.send_sats("sunupay_treasury", address, amount_sats)
        self.mine(1)
        return transaction_id
